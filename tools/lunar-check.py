def sun_lon(jde):         # 太阳视黄经（度）
    T = (jde - 2451545.0)/36525
    L0 = 280.46646 + 36000.76983*T + 0.0003032*T*T
    M  = 357.52911 + 35999.05029*T - 0.0001537*T*T
    C  = ((1.914602 - 0.004817*T - 0.000014*T*T)*math.sin(D(M))
          + (0.019993 - 0.000101*T)*math.sin(D(2*M)) + 0.000289*math.sin(D(3*M)))
    Om = 125.04 - 1934.136*T
    return (L0 + C - 0.00569 - 0.00478*math.sin(D(Om))) % 360

def jd_to_ymd(jd):        # 儒略日 -> 公历 y,m,d（含小数日）
    jd += 0.5; Z = int(jd); Fr = jd - Z
    if Z < 2299161: A = Z
    else:
        a = int((Z - 1867216.25)/36524.25); A = Z + 1 + a - a//4
    B = A + 1524; C = int((B - 122.1)/365.25); Dd = int(365.25*C)
    Ee = int((B - Dd)/30.6001)
    day = B - Dd - int(30.6001*Ee) + Fr
    mo = Ee - 1 if Ee < 14 else Ee - 13
    yr = C - 4716 if mo > 2 else C - 4715
    return yr, mo, day

def beijing_date(jde, year_hint=2026):   # TT 的 JDE -> 北京时的公历日期序号（整日 JD）
    jd_ut = jde - deltaT(year_hint)/86400.0
    return math.floor(jd_ut + 8/24.0 + 0.5)      # +8h 时区，floor 到当地日

def solve_term(target, jd_guess):        # 求太阳视黄经=target 的时刻（TT JDE）
    lo, hi = jd_guess - 20, jd_guess + 20
    f = lambda x: ((sun_lon(x) - target + 180) % 360) - 180
    for _ in range(80):
        mid = (lo + hi)/2
        if f(lo)*f(mid) <= 0: hi = mid
        else: lo = mid
    return (lo + hi)/2

