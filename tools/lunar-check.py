def deltaT(y):            # 2026 年 ΔT ≈ 72s（Espenak/Meeus 多项式）
    t = y - 2000.0
    return 62.92 + 0.32217*t + 0.005589*t*t

def newmoon_jde(k):       # Meeus 49.1 + 表 49.A + 行星修正，返回 TT 的 JDE
    T = k/1236.85
    jde = (2451550.09766 + 29.530588861*k + 0.00015437*T**2
           - 0.000000150*T**3 + 0.00000000073*T**4)
