def moon_lon(jde):                      # 月球几何地心黄经（度），Meeus 47
    T = (jde-2451545.0)/36525
    Lp = 218.3164477 + 481267.88123421*T - 0.0015786*T**2 + T**3/538841 - T**4/65194000
    D  = 297.8501921 + 445267.1114034*T - 0.0018819*T**2 + T**3/545868 - T**4/113065000
    M  = 357.5291092 + 35999.0502909*T - 0.0001536*T**2 + T**3/24490000
    Mp = 134.9633964 + 477198.8675055*T + 0.0087414*T**2 + T**3/69699 - T**4/14712000
    F  = 93.2720950 + 483202.0175233*T - 0.0036539*T**2 - T**3/3526000 + T**4/863310000
    A1 = 119.75 + 131.849*T; A2 = 53.09 + 479264.290*T
    E  = 1 - 0.002516*T - 0.0000074*T*T
    s = 0.0
    for d,m,mp,f,c in T47:
        arg = d*D + m*M + mp*Mp + f*F
        s += c * (E**abs(m)) * math.sin(R(arg))
    s += 3958*math.sin(R(A1)) + 1962*math.sin(R(Lp-F)) + 318*math.sin(R(A2))
    return (Lp + s/1e6) % 360

def sun_lon_geo(jde):                   # 太阳几何黄经（度），Meeus 25
    T = (jde-2451545.0)/36525
    L0 = 280.46646 + 36000.76983*T + 0.0003032*T*T
    M  = 357.52911 + 35999.05029*T - 0.0001537*T*T
    C  = ((1.914602-0.004817*T-0.000014*T*T)*math.sin(R(M))
          + (0.019993-0.000101*T)*math.sin(R(2*M)) + 0.000289*math.sin(R(3*M)))
    return (L0 + C) % 360

def elong(jde, apparent=True):
    ml, sl = moon_lon(jde), sun_lon_geo(jde)
    if apparent:                        # 太阳光行差 -20.5"；月球光行时改正 ≈ -0.70"
        sl -= 20.4898/3600
        ml -= 0.704/3600
    return ((ml - sl + 180) % 360) - 180

def deltaT_espenak(y): t=y-2000.0; return 62.92 + 0.32217*t + 0.005589*t*t

def solve(lo, hi, apparent):
    f = lambda x: elong(x, apparent)
    for _ in range(100):
        mid=(lo+hi)/2
        if f(lo)*f(mid) <= 0: hi=mid
        else: lo=mid
    return (lo+hi)/2

def fmt(jde, dT):
    bj = jde - dT/86400.0 + 8/24.0      # TT -> UT -> 北京时
    import datetime
    days = bj - 2451544.5               # 自 2000-01-01 00:00 起的天数
    dt = datetime.datetime(2000,1,1) + datetime.timedelta(days=days)
    return dt.strftime('%Y-%m-%d %H:%M:%S')

